"""Build the dependency-free browser bundle from the two shared-scope sources."""
from pathlib import Path

root = Path(__file__).resolve().parents[1] / 'web'
editor = (root / 'src/editor.js').read_text(encoding='utf-8')
connection = (root / 'src/connection.js').read_text(encoding='utf-8')
assert editor.count('/* EXECUTION_SERVICE */') == 1
(root / 'app.js').write_text('// Generated by workbench/scripts/build-web.py. Edit web/src/.\n' +
                             editor.replace('/* EXECUTION_SERVICE */', connection.rstrip()),
                             encoding='utf-8')
