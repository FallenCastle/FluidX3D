import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, join, parse } from 'node:path';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
const root=fileURLToPath(new URL('../',import.meta.url));
const result=await build({entryPoints:[root+'web/src/results.js'],bundle:true,minify:true,format:'iife',target:['safari16','chrome110'],outfile:root+'web/results.js',legalComments:'linked',loader:{'.glsl':'text'},metafile:true});
const packages=new Map();
for(const input of Object.keys(result.metafile.inputs)){
  if(!input.includes('node_modules/'))continue;
  let directory=dirname(input);
  while(directory!==parse(directory).root){
    const manifest=join(directory,'package.json');
    if(existsSync(manifest)){
      const pkg=JSON.parse(readFileSync(manifest,'utf8'));
      if(pkg.name){packages.set(pkg.name,{directory,pkg});break;}
    }
    directory=dirname(directory);
  }
}
let notices='Third-party packages included in results.js. Generated by build-results.mjs.\n';
for(const [name,{directory,pkg}] of [...packages].sort()){
  const files=readdirSync(directory).filter(f=>/^(licen[sc]e|copyright)(\.[a-z]+)?$/i.test(f));
  if(!files.length){
    if(name!=='seedrandom')throw Error('Missing license: '+name);
    notices+='\n\n===== '+name+' '+pkg.version+' ('+pkg.license+') =====\n';
    notices+=readFileSync(join(directory,'seedrandom.js'),'utf8').match(/^\/\*[\s\S]*?\*\//)[0]+'\n';
    for(const input of Object.keys(result.metafile.inputs).filter(f=>f.startsWith(directory+'/lib/'))){
      const source=readFileSync(input,'utf8');
      const comment=source.match(/\/\*[\s\S]*?\*\//);
      if(comment)notices+=comment[0]+'\n';
    }
    continue;
  }
  notices+='\n\n===== '+name+' '+pkg.version+' ('+pkg.license+') =====\n';
  for(const file of files)notices+='\n'+readFileSync(join(directory,file),'utf8')+'\n';
}
writeFileSync(root+'web/licenses/THIRD-PARTY.txt',notices);
